# -*- coding: utf-8 -*-
"""SUMMARY.md for the region-target TI atlas, generated from the tables collect_targets.py wrote
(results_v22/v22_target_atlas_300). Aggregates only. 18 Oct 2026.

    python pipeline/nchc/summarize_targets.py
"""
import csv
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(os.path.dirname(HERE)), "results_v22", "v22_target_atlas_300")


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def main():
    S = list(csv.DictReader(open(os.path.join(OUT, "target_summary.csv"), encoding="utf-8")))
    A = list(csv.DictReader(open(os.path.join(OUT, "agreement_vs_fem.csv"), encoding="utf-8")))
    D = list(csv.DictReader(open(os.path.join(OUT, "demographics.csv"), encoding="utf-8")))
    prov = json.load(open(os.path.join(OUT, "PROVENANCE.json"), encoding="utf-8"))
    fem = {r["target"]: r for r in S if r["model"] == "fem"}
    res = [r for r in fem.values() if int(r["heads_resolvable"]) > 0]
    L = ["# TI target atlas over the 300-head cohort (FEM, SPICEhead 2 / 1 / 5 mm)", "",
         f"Generated by `pipeline/nchc/summarize_targets.py` from the tables beside this file. Collected "
         f"{prov['collected']}: {prov['n_heads']} heads × {prov['n_targets']} targets × {prov['n_montages']:,} two-pair 10-20 montages, "
         "4 models. This is a new results set for Paper C. It is not in any Results record or manuscript.", "",
         "**Definitions**", "",
         "- **F** = median TI envelope over the target grey matter ÷ 99th percentile over grey matter more than 20 mm away "
         "(F > 1: the target receives more than almost all distant cortex).",
         "- **Individual optimum** = best of the 11,628 montages for that head.",
         "- **Cohort montage** = the montage with the highest median F across heads.",
         "- **Personalization gain** = F at the individual optimum ÷ F at the cohort montage in the same head.",
         "- **T** = the target envelope at 1 mA per channel. It scales linearly with current.", "",
         "**Checks**", "",
         f"- The six Paper A targets were rescored on every head. They match the collected 300-head scores within 6.6e-7, "
         f"with all 5,400 winners identical, and the cohort winners are identical ({prov['ref6_cohort_winners_match_collected']}).",
         "- Every score file was SHA-256 verified after download.", "",
         "## Reach (FEM, individual optimum)", "",
         "| Set | Targets | F median across targets [range] | Targets with F > 1 in most heads | Median personalization gain [range] |",
         "|---|---|---|---|---|"]
    for tier, lab in (("tier1", "Tier 1: AAL90"), ("tier2", "Tier 2: psychiatric"), ("ref6", "Paper A targets")):
        sub = [r for r in res if r["tier"] == tier]
        Fi = np.array([f(r["F_ind_median"]) for r in sub]); G = np.array([f(r["gain_median"]) for r in sub])
        P = np.array([f(r["heads_F_ind_above_1_pct"]) for r in sub])
        L.append(f"| {lab} | {len(sub)} | {np.median(Fi):.2f} [{Fi.min():.2f}–{Fi.max():.2f}] | {int((P > 50).sum())} | "
                 f"{np.median(G):.3f} [{G.min():.3f}–{G.max():.3f}] |")
    unres = [r["target"] for r in fem.values() if int(r["heads_resolvable"]) == 0]
    L += ["", f"Not resolvable in any head: {', '.join(unres) or 'none'}. These structures have no grey-matter voxels "
          "in the CHARM segmentation. White-matter targets were not scored.", "",
          "### Tier 2 (FEM)", "",
          "| Target | F median | Heads with F > 1 | T (V/m per mA) | Cohort montage | Gain median | Heads gaining ≥ 10 % |",
          "|---|---|---|---|---|---|---|"]
    for r in [r for r in S if r["model"] == "fem" and r["tier"] == "tier2"]:
        if int(r["heads_resolvable"]) == 0:
            L.append(f"| {r['target']} | – | – | – | not resolvable | – | – |"); continue
        L.append(f"| {r['target']} | {f(r['F_ind_median']):.2f} | {f(r['heads_F_ind_above_1_pct']):.0f} % | "
                 f"{f(r['T_ind_median_Vm_per_mA']):.3f} | {r['cohort_montage']} | {f(r['gain_median']):.3f} | {f(r['heads_gain_ge_10pct']):.0f} % |")
    t1 = sorted([r for r in res if r["tier"] == "tier1"], key=lambda r: f(r["F_ind_median"]))
    L += ["", "### Tier 1 (FEM): least and most focally reachable AAL regions", "",
          "| Least reachable | F median | Most reachable | F median |", "|---|---|---|---|"]
    for lo, hi in zip(t1[:8], t1[::-1][:8]):
        L.append(f"| {lo['target']} | {f(lo['F_ind_median']):.2f} | {hi['target']} | {f(hi['F_ind_median']):.2f} |")
    L += ["", "## SPICEhead against FEM (all resolvable targets, 300 heads each)", "",
          "| Model | ρ over montages: median of target medians [worst target] | FEM optimum kept by the model's winner: median [worst target's 5th pct] | Same individual winner (median over targets) | Cohort winner = FEM | Head × target rows keeping < 90 % |",
          "|---|---|---|---|---|---|"]
    for m, lab in (("sp1", "SPICEhead 1 mm"), ("sp2", "SPICEhead 2 mm"), ("sp5", "SPICEhead 5 mm")):
        sub = [r for r in A if r["model"] == m and r.get("rho_median") not in ("", None)]
        rho = np.array([f(r["rho_median"]) for r in sub]); k = np.array([f(r["fem_optimum_kept_median"]) for r in sub])
        k5 = np.array([f(r["fem_optimum_kept_p5"]) for r in sub]); sw = np.array([f(r["same_individual_winner_pct"]) for r in sub])
        cw = sum(r["cohort_winner_same_as_fem"] == "True" for r in sub); low = sum(int(f(r["rows_kept_below_90_pct"])) for r in sub)
        L.append(f"| {lab} | {np.median(rho):.3f} [{rho.min():.3f}] | {np.median(k):.1f} % [{k5.min():.1f} %] | {np.median(sw):.0f} % | "
                 f"{cw}/{len(sub)} | {low:,}/{len(sub) * 300:,} |")
    L += ["", "At 1 mm the SPICEhead ranking of montages is almost the FEM ranking. At 2 mm it is close. At 5 mm the agreement "
          "drops substantially: the winners rarely match, and the 5 mm choice often loses a sizeable share of the FEM "
          "optimum. **This bears on any 5 mm cohort result in Paper A. It needs an author decision before anything is "
          "changed.**", "",
          "## Age, sex and site (FEM, individual optimum; BH-FDR across targets)", ""]
    fa = [d for d in D if d["model"] == "fem"]
    r = np.array([f(d["rho_age_F"]) for d in fa]); rt = np.array([f(d["rho_age_T"]) for d in fa])
    nF = sum(f(d["q_age_F"]) < 0.05 for d in fa); nFn = sum(f(d["q_age_F"]) < 0.05 and f(d["rho_age_F"]) < 0 for d in fa)
    nT = sum(f(d["q_age_T"]) < 0.05 for d in fa); nTn = sum(f(d["q_age_T"]) < 0.05 and f(d["rho_age_T"]) < 0 for d in fa)
    nG = sum(f(d["q_age_gain"]) < 0.05 for d in fa)
    L += [f"- **Focality F vs age:** median Spearman ρ {np.median(r):.2f} (range {r.min():.2f} to {r.max():.2f}). "
          f"q < 0.05 in {nF}/{len(fa)} targets: {nFn} decline with age, {nF - nFn} rise.",
          f"- **Target field T vs age:** median ρ {np.median(rt):.2f}. q < 0.05 in {nT}/{len(fa)} targets ({nTn} decline).",
          f"- **Personalization gain vs age:** q < 0.05 in {nG}/{len(fa)} targets. See demographics.csv for direction and "
          "the sex and site medians.", "",
          "Strongest age effects on F (FEM):", "", "| Target | ρ(age, F) | q | ρ(age, T) |", "|---|---|---|---|"]
    for d in sorted(fa, key=lambda d: f(d["rho_age_F"]))[:6] + sorted(fa, key=lambda d: -f(d["rho_age_F"]))[:3]:
        L.append(f"| {d['target']} | {f(d['rho_age_F']):.2f} | {f(d['q_age_F']):.1e} | {f(d['rho_age_T']):.2f} |")
    L += ["", "## Files", "",
          "- `target_summary.csv`: one row per target × model (reach, T, cohort montage, personalization gain).",
          "- `agreement_vs_fem.csv`: one row per target × SPICEhead model.",
          "- `demographics.csv`: age correlations with q-values, and sex and site medians.",
          "- Per-head arrays (h-codes only): `L:\\BrainProbe\\SPICEhead\\nchc_fullsearch\\target_atlas_perhead.npz`.", "",
          "## Caveats", "",
          "- Optimality is conditional on the 19-electrode 10-20 candidate set, two pairs with equal currents, the GM-only "
          "metric and the stated conductivities.",
          "- FEM and SPICEhead differ in electrode model (24 mm pads vs 12 mm skin contacts). The insula disagreement found "
          "in the 300-head comparison is genuine (re-mesh check, results_v22/v22_fem_fullsearch_300/REMESH_CHECK_2026-10-18.md).",
          "- Targets are atlas regions warped by CHARM's non-linear MNI registration. AAL regions are whole gyri. "
          "Tier-2 spheres use literature MNI coordinates (Fox et al. 2012).",
          "- One head used the validated fallback warp, because its CHARM folder lacks MNI2Conform_nonl (pipeline/nchc/warp_fallback.py)."]
    open(os.path.join(OUT, "SUMMARY.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("wrote", os.path.join(OUT, "SUMMARY.md"))


if __name__ == "__main__":
    main()
