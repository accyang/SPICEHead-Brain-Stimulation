# -*- coding: utf-8 -*-
"""SUMMARY.md for the v2 target atlas (constrained optimum, top band, accessibility tie-break). 22 Oct 2026.

    python pipeline/nchc/summarize_targets_v2.py
"""
import csv
import json
import os

import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(HERE)))
from spicehead import config                                          # noqa: E402
OUT = os.path.join(config.RESULTS, f"{config.MODEL}_target_atlas_300")    # v22: results_v22/v22_target_atlas_300


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def main():
    S = list(csv.DictReader(open(os.path.join(OUT, "target_summary.csv"), encoding="utf-8")))
    A = list(csv.DictReader(open(os.path.join(OUT, "agreement_vs_fem.csv"), encoding="utf-8")))
    D = list(csv.DictReader(open(os.path.join(OUT, "demographics.csv"), encoding="utf-8")))
    prov = json.load(open(os.path.join(OUT, "PROVENANCE.json"), encoding="utf-8"))
    rule = prov["rule"]
    fem = [r for r in S if r["model"] == "fem" and int(r["heads_resolvable"]) > 0]
    mv = prov.get("model_version", "v22")
    if mv == "v22":
        head = (f"Generated by `pipeline/nchc/summarize_targets_v2.py`. Recomputed {prov['collected_v2']} from the scores collected "
                f"{prov['collected']} ({prov['n_heads']} heads × {prov['n_targets']} targets × {prov['n_montages']:,} montages, FEM and SPICEhead 2 / 1 / 5 mm). "
                "The rule change was approved by the PI on 22 Oct after the logic audit (OPTIMIZATION_LOGIC_AUDIT_2026-10-22.md). "
                "The earlier, unconstrained tables are in `unconstrained_2026-10-18/`. New results set for Paper C; not in any record.")
    else:   # other model versions (v23 since 24 Oct 2026): own wording, only the grids actually scored
        grids = " / ".join(m[2:] for m in prov.get("models", []) if m.startswith("sp"))
        head = (f"Generated by `pipeline/nchc/summarize_targets_v2.py` for SPICEhead model {mv}. Collected {prov['collected_v2']} "
                f"({prov['n_heads']} heads × {prov['n_targets']} targets × {prov['n_montages']:,} montages, FEM and SPICEhead {mv} {grids} mm). "
                "Same constrained-optimum and top-band rule as the v22 atlas (approved 22 Oct after the logic audit). "
                "Not in any record; never mix these numbers with the v22 atlas.")
    L = ["# TI target atlas over the 300-head cohort, v2: constrained optimum and top band" + ("" if mv == "v22" else f" (model {mv})"), "",
         head, "",
         "**Rule**", "",
         f"- A montage is admissible if its target field T is at least {100*rule['T_min_fraction_of_achievable']:.0f} % of the highest T any "
         "montage gives that target in that head. The constrained optimum is the admissible montage with the highest F = T/O.",
         f"- The top band is every admissible montage with F within {100*rule['band_fraction_of_best_F']:.0f} % of the constrained optimum. "
         f"The reported choice is the band member with the most easy electrodes ({', '.join(rule['easy_electrodes'])}), then the highest F.",
         "- Cohort level: the same rule on the medians of F and T across resolvable heads. Personalization gain = the head's constrained "
         "optimum F ÷ F at the cohort choice in that head.",
         "- F > 1 means the target receives more than the 99th percentile of grey matter farther than 20 mm away. T is at 1 mA per channel.", "",
         "**Checks**", "",
         f"- Unconstrained ref6 cohort winners equal the collected 300-head comparison: {prov['ref6_unconstrained_cohort_winners_match_collected']}.",
         "- Every score file was SHA-256 verified after download.", "",
         "## What the constraint changes (FEM)", "",
         "| Set | Targets | F, unconstrained → constrained (median across targets) | F cost of the constraint, median | Target field gain, median | Choice with ≥ 3 easy electrodes |",
         "|---|---|---|---|---|---|"]
    for tier, lab in (("tier1", "Tier 1: AAL90"), ("tier2", "Tier 2: psychiatric"), ("ref6", "Paper A targets")):
        sub = [r for r in fem if r["tier"] == tier]
        f0 = np.median([f(r["F_unconstrained_median"]) for r in sub]); fc = np.median([f(r["F_constrained_median"]) for r in sub])
        cost = np.median([f(r["F_cost_of_constraint_pct_median"]) for r in sub]); tg = np.median([f(r["T_gain_of_constraint_median"]) for r in sub])
        ez = sum(f(r["choice_easy_electrodes_mean"]) >= 3 for r in sub)
        L.append(f"| {lab} | {len(sub)} | {f0:.2f} → {fc:.2f} | {cost:.1f} % | ×{tg:.2f} | {ez}/{len(sub)} |")
    L += ["", "### Tier 2 (FEM)", "",
          "| Target | F constrained (median) | Heads with F > 1 | T (V/m per mA) | T gain vs unconstrained | Band size | Cohort choice | Easy electrodes | Gain median |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in [r for r in S if r["model"] == "fem" and r["tier"] == "tier2"]:
        if int(r["heads_resolvable"]) == 0:
            L.append(f"| {r['target']} | – | – | – | – | – | not resolvable | – | – |"); continue
        L.append(f"| {r['target']} | {f(r['F_constrained_median']):.2f} | {f(r['heads_F_constrained_above_1_pct']):.0f} % | {f(r['T_constrained_median_Vm_per_mA']):.3f} | "
                 f"×{f(r['T_gain_of_constraint_median']):.2f} | {r['band_size_median']} | {r['cohort_choice']} | {r['cohort_choice_easy_electrodes']}/4 | {f(r['gain_median']):.3f} |")
    deep = ["ref6:thalamus", "Thalamus_L", "Thalamus_R", "MDthal_L", "MDthal_R", "Pulvinar_L", "Pulvinar_R", "NAcc_L", "NAcc_R",
            "Hippocampus_L", "Hippocampus_R", "Amygdala_L", "Amygdala_R", "Caudate_L", "Caudate_R", "Putamen_L", "Putamen_R", "Pallidum_L", "Pallidum_R"]
    L += ["", "### Deep targets (FEM): field delivered under each rule", "",
          "| Target | T unconstrained (V/m per mA) | T constrained | T achievable (max) | F unconstrained → constrained |", "|---|---|---|---|---|"]
    for n in deep:
        r = next((r for r in fem if r["target"] == n), None)
        if r:
            L.append(f"| {n} | {f(r['T_unconstrained_median_Vm_per_mA']):.3f} | {f(r['T_constrained_median_Vm_per_mA']):.3f} | {f(r['T_max_median_Vm_per_mA']):.3f} | "
                     f"{f(r['F_unconstrained_median']):.2f} → {f(r['F_constrained_median']):.2f} |")
    L += ["", "## Top band and accessibility (FEM)", ""]
    nb = np.array([f(r["band_size_median"]) for r in fem]); sp = np.array([f(r["band_F_spread_pct_median"]) for r in fem])
    ea = np.array([f(r["choice_easy_electrodes_mean"]) for r in fem]); e0 = np.array([f(r["unconstrained_winner_easy_electrodes_mean"]) for r in fem])
    cb = np.array([f(r["cohort_band_size"]) for r in fem])
    L += [f"- Per head, the band holds a median of {np.median(nb):.0f} montages (across targets; range {nb.min():.0f}–{nb.max():.0f}), spanning "
          f"{np.median(sp):.1f} % of F. The reported choice averages {np.mean(ea):.2f} easy electrodes of 4, against {np.mean(e0):.2f} for the "
          "unconstrained winner.",
          f"- At cohort level the band holds a median of {np.median(cb):.0f} montages; the cohort choice is listed per target in target_summary.csv.", "",
          "## SPICEhead against FEM (constrained choices, all resolvable targets)", "",
          "| Model | ρ over montages, median of target medians [worst] | Same choice as FEM (median over targets) | Choice inside FEM's band | FEM optimum kept, median [worst target's 5th pct] | Cohort choice = FEM | Rows keeping < 90 % |",
          "|---|---|---|---|---|---|---|"]
    for m, lab in (("sp1", "SPICEhead 1 mm"), ("sp2", "SPICEhead 2 mm"), ("sp5", "SPICEhead 5 mm")):
        sub = [r for r in A if r["model"] == m and r.get("rho_median") not in ("", None)]
        if not sub:                                                   # e.g. no 5 mm scores under v23
            continue
        rho = np.array([f(r["rho_median"]) for r in sub]); sw = np.array([f(r["same_choice_pct"]) for r in sub]); ib = np.array([f(r["choice_inside_fem_band_pct"]) for r in sub])
        k = np.array([f(r["fem_optimum_kept_median"]) for r in sub]); k5 = np.array([f(r["fem_optimum_kept_p5"]) for r in sub])
        cw = sum(r["cohort_choice_same_as_fem"] == "True" for r in sub); low = sum(int(f(r["rows_kept_below_90_pct"])) for r in sub)
        L.append(f"| {lab} | {np.median(rho):.3f} [{rho.min():.3f}] | {np.median(sw):.0f} % | {np.median(ib):.0f} % | {np.median(k):.1f} % [{k5.min():.1f} %] | {cw}/{len(sub)} | {low:,}/{len(sub)*300:,} |")
    L += ["", "## Age (FEM, constrained optimum; BH-FDR across targets)", ""]
    fa = [d for d in D if d["model"] == "fem"]
    r_ = np.array([f(d["rho_age_F"]) for d in fa]); rt = np.array([f(d["rho_age_T"]) for d in fa])
    nF = sum(f(d["q_age_F"]) < 0.05 for d in fa); nFn = sum(f(d["q_age_F"]) < 0.05 and f(d["rho_age_F"]) < 0 for d in fa)
    nT = sum(f(d["q_age_T"]) < 0.05 for d in fa); nTn = sum(f(d["q_age_T"]) < 0.05 and f(d["rho_age_T"]) < 0 for d in fa)
    L += [f"- F vs age: median ρ {np.median(r_):.2f}; q < 0.05 in {nF}/{len(fa)} targets ({nFn} decline, {nF-nFn} rise).",
          f"- T vs age: median ρ {np.median(rt):.2f}; q < 0.05 in {nT}/{len(fa)} targets ({nTn} decline).",
          f"- Gain vs age: q < 0.05 in {sum(f(d['q_age_gain']) < 0.05 for d in fa)}/{len(fa)} targets. Direction, sex and site medians in demographics.csv.", "",
          "## Files", "",
          "- `target_summary.csv`: per target × model; unconstrained and constrained optimum, band, choice, cohort choice, gain.",
          "- `agreement_vs_fem.csv`, `demographics.csv`; per-head arrays (h-codes) in `L:\\BrainProbe\\SPICEhead\\nchc_fullsearch\\target_atlas_perhead_v2.npz`.", "",
          "## Caveats", "",
          f"- The {100*rule['T_min_fraction_of_achievable']:.0f} % field threshold and the {100*rule['band_fraction_of_best_F']:.0f} % band are design choices fixed on 22 Oct, before the recomputation.",
          "- Optimality remains conditional on the 19-electrode 10-20 set, two equal-current pairs, the GM-only metric and the conductivities.",
          "- Electrode models differ between FEM (24 mm pads) and SPICEhead (12 mm skin contacts); see the 300-head comparison and its re-mesh check.",
          "- Targets are atlas regions warped by CHARM's non-linear registration; one head used the validated fallback warp."]
    open(os.path.join(OUT, "SUMMARY.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("wrote", os.path.join(OUT, "SUMMARY.md"))


if __name__ == "__main__":
    main()
